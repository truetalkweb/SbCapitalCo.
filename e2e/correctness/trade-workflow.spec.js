import { test, expect } from '@playwright/test';
import { setupApp, initialWorkspace } from '../support/appHarness.js';

const now = Date.parse('2026-10-08T15:00:00Z');
const navigate = async (page, name, width) => {
  if (width < 800) await page.getByRole('button', { name: 'Open workspace navigation' }).click();
  await page.getByRole('navigation', { name: 'Terminal workspaces' }).getByRole('button', { name, exact: true }).click();
};

for (const width of [390, 1536]) test(`scanner plan reaches charts, paper execution and journal at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 1024 });
  await page.clock.setFixedTime(now);
  const row = symbol => ({ symbol, price: 100, volume: 1000000, changePercent: 2, source: 'Isolated provider', providerTimestamp: new Date(now).toISOString(), verified: true });
  const evidence = await setupApp(page, { ...initialWorkspace, activeWorkspace: 'scanner', layoutMode: '1', positions: {}, orders: [], journalEntries: [] },
    { providerQuotes: ['AAPL', 'MSFT'].map(symbol => ({ symbol, price: 100, source: 'Isolated provider', timestamp: now / 1000 })),
      providerScanner: { gainers: [row('AAPL'), row('MSFT')], verifiedMovers: [row('AAPL'), row('MSFT')], coverage: 'bounded-universe' } });
  await page.getByLabel('Minimum relative volume', { exact: true }).selectOption('0');
  await page.getByRole('row', { name: 'Select AAPL', exact: true }).first().click();
  await page.getByLabel('Plan setup', { exact: true }).fill('Opening breakout');
  await page.getByLabel('Plan stop loss', { exact: true }).fill('95');
  await page.getByLabel('Plan take profit', { exact: true }).fill('110');
  await page.getByLabel('Plan notes', { exact: true }).fill('Wait for volume confirmation');
  await page.getByRole('row', { name: 'Select MSFT', exact: true }).first().click();
  await expect(page.getByLabel('Plan setup', { exact: true })).toHaveValue('');
  await page.getByLabel('Plan setup', { exact: true }).fill('Separate MSFT plan');
  await page.getByRole('row', { name: 'Select AAPL', exact: true }).first().click();
  await expect(page.getByLabel('Plan setup', { exact: true })).toHaveValue('Opening breakout');
  await page.getByRole('button', { name: 'Open Chart', exact: true }).click();
  await expect(page.getByLabel('Plan notes', { exact: true })).toHaveValue('Wait for volume confirmation');
  await page.getByLabel('Plan notes', { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('chart-trade-plan.png'), fullPage: true });
  await expect.poll(() => evidence.workspace().activeWorkspace).toMatch(/charts|chart-analysis/);
  await page.reload();
  await expect(page.getByLabel('Plan stop loss', { exact: true })).toHaveValue('95');
  expect(evidence.workspace().paperLedger.orders).toHaveLength(0);
  await page.getByRole('button', { name: 'Review Order', exact: true }).click();
  const ticket = page.getByRole('region', { name: 'Paper trade ticket', exact: true });
  await expect(ticket.getByLabel('Paper setup', { exact: true })).toHaveValue('Opening breakout');
  await expect(ticket.getByLabel('Stop loss', { exact: true })).toHaveValue('95');
  await expect(ticket.getByLabel('Take profit', { exact: true })).toHaveValue('110');
  await ticket.getByLabel('Paper order type').selectOption('MARKET');
  await ticket.getByLabel('Paper quantity').fill('5');
  await ticket.getByLabel('Paper plan notes').fill('Waited for volume confirmation');
  await navigate(page, 'Charts', width);
  await expect(page.getByLabel('Plan notes', { exact: true })).toHaveValue('Waited for volume confirmation');
  await page.getByRole('button', { name: 'Review Order', exact: true }).click();
  await expect.poll(() => evidence.workspace().activeWorkspace).toBe('orders');
  await page.reload();
  await expect(ticket.getByLabel('Paper quantity')).toHaveValue('5');
  await expect(ticket.getByLabel('Paper order type')).toHaveValue('MARKET');
  await expect(ticket.getByLabel('Paper plan notes')).toHaveValue('Waited for volume confirmation');
  expect(evidence.workspace().paperLedger.orders).toHaveLength(0);
  await ticket.getByRole('button', { name: 'Place Paper Buy', exact: true }).click();
  await expect(ticket.getByRole('status')).toContainText('FILLED');
  await expect.poll(() => evidence.workspace().paperLedger.positions.AAPL?.tradePlan?.notes).toBe('Waited for volume confirmation');
  const management = page.getByRole('region', { name: 'Paper account management', exact: true });
  await management.getByRole('button', { name: 'Close AAPL', exact: true }).click();
  await management.getByRole('button', { name: 'Confirm paper action', exact: true }).click();
  await expect.poll(() => Object.keys(evidence.workspace().paperLedger.positions)).toEqual([]);
  await navigate(page, 'Trade Journal', width);
  const record = page.getByRole('row', { name: 'Select AAPL', exact: true });
  await expect(record).toContainText('Opening breakout');
  await expect(record).toContainText('Waited for volume confirmation');
  await record.getByText('Entry plan', { exact: true }).click();
  await expect(record).toContainText('First entry stop: $95.00');
  await expect(record).toContainText('target: $110.00');
  await page.getByRole('tab', { name: 'Exports', exact: true }).click();
  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Journal CSV', exact: true }).click();
  const stream = await (await pending).createReadStream();
  let csv = ''; for await (const chunk of stream) csv += chunk;
  expect(csv).toContain('entryPlanNotes,firstEntryStopLoss,firstEntryTakeProfit');
  expect(csv).toContain('"Waited for volume confirmation","95","110"');
  await page.getByRole('tab', { name: 'Overview', exact: true }).click();
  await record.getByText('Entry plan', { exact: true }).scrollIntoViewIfNeeded();
  await record.getByText('Entry plan', { exact: true }).click();
  await page.screenshot({ path: info.outputPath('journal-entry-plan.png'), fullPage: true });
  expect(evidence.errors).toEqual([]);
  expect(evidence.blocked).toEqual([]);
});
